export function translate(order: LanguageOrder, key: string, values?: Record<string, string | number>) {
  const message = order.map((language) => messages[language][key]).find(Boolean) ?? key;
  return message.replace(/\{(\w+)\}/g, (match: string, name: string) =>
    values?.[name] === undefined ? match : String(values[name]),
  );
}

export function isLanguageOrder(value: unknown): value is LanguageOrder {
  return (
    Array.isArray(value) &&
    value.length === languages.length &&
    languages.every((language) => value.includes(language))
  );
}
